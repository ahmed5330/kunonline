import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read = path => readFileSync(new URL('../'+path,import.meta.url),'utf8');
const base = 'android/app/src/main/java/com/kunonline/callerid/';
const theme = read(base+'KunDesignSystem.kt');
const v3 = read(base+'KunDesignV3.kt');
const app = read(base+'KunNativeAppV25.kt');
const sections = read(base+'KunSystemSections.kt');
const chat = read(base+'MobileCollaboration.kt');
const search = read(base+'GlobalOrderSearch.kt');
const calls = read(base+'CallerOverlay.kt');
const service = read(base+'CustomerServiceMobileV23.kt');
const version = read('android/app/build.gradle.kts');
for (const hex of ['0xFF123A62','0xFF15599B','0xFFF3F7FB','0xFF16A773','0xFFE9A21F','0xFFDD5364']) assert.ok(v3.includes(hex),'missing brand token '+hex);
for (const item of ['KunGreetingHero','KunRaisedHomeIcon','KunAsyncPanel','KunSectionListCard']) assert.ok(v3.includes('fun '+item+'('),'missing reusable UI '+item);
assert.ok(theme.includes('0xFFF3F7FB') && theme.includes('0xFF15599B'));
assert.ok(app.includes('KunGreetingHero(name = displayName'));
assert.ok(app.includes('statusRows.chunked(3)'));
assert.ok(app.includes('onOpenCollaboration') && app.includes('onOpenSystemSections'));
assert.ok(app.includes('GlobalOrderSearchDialog('));
for(const button of ['"الطلبات"','"العملاء"','"الرئيسية"','"التواصل"','"الأقسام"']) assert.ok(app.includes(button),'removed nav feature '+button);
assert.ok(sections.includes('KunSectionListCard('));
for(const k of ['PRINTING','FINANCE','ACCOUNTING','CAMPAIGNS','INVENTORY','RETURNS','WALLET','INTEGRATIONS','SETTINGS']) assert.ok(sections.includes('NativeClientSection.'+k),'lost section '+k);
for(const k of ['Icons.Outlined.AddComment','Icons.Outlined.Refresh','Icons.Outlined.Storefront','Icons.Outlined.Send','MobileChatApi.send(']) assert.ok(chat.includes(k),'lost chat behavior '+k);
assert.ok(chat.includes('chatQuery') && chat.includes('جاري تحميل الرسائل'));
assert.ok(search.includes('GlobalOrderSearchApi.search') && search.includes('كل المتاجر المسموح بها'));
for(const k of ['"confirmed"','"no_answer"','"cancelled"','CallerJntOrderEditActivity.EXTRA_SHIPPING_ONLY']) assert.ok(calls.includes(k),'lost in-call action '+k);
assert.ok(service.includes('KunCustomerServiceApi.claimContact') && service.includes('selected = stateFilter == key'));
assert.match(version,/versionCode\s*=\s*143/);
assert.match(version,/versionName\s*=\s*"2\.9\.12"/);
console.log('PASS: Kun Online Android reviewed UX navigation, features, statuses, themes and release contract');
