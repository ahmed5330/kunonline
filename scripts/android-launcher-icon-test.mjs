import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const root = 'android/app/src/main';
const manifest = readFileSync(root + '/AndroidManifest.xml','utf8');
const icon = readFileSync(root + '/res/mipmap-anydpi-v26/ic_launcher.xml','utf8');
const foreground = readFileSync(root + '/res/drawable/kun_launcher_foreground.xml','utf8');
const nativeLogo = readFileSync(root + '/res/drawable-nodpi/kun_logo.png');
const webLogo = readFileSync('public/logo.png');
assert.match(manifest,/android:icon="@mipmap\/ic_launcher"/);
assert.match(manifest,/android:roundIcon="@mipmap\/ic_launcher"/);
assert.match(icon,/<adaptive-icon/);
assert.match(icon,/<background android:drawable="@android:color\/white"/);
assert.match(icon,/<foreground android:drawable="@drawable\/kun_launcher_foreground"/);
assert.match(foreground,/@drawable\/kun_logo/);
assert.deepEqual(nativeLogo,webLogo,'Android launcher icon must use the actual unmodified official Kun Online logo');
const gradle = readFileSync('android/app/build.gradle.kts','utf8');
assert.ok(Number(gradle.match(/versionCode\s*=\s*(\d+)/)?.[1]||0)>=132,'Launcher build code must not regress');
assert.match(gradle,/versionName\s*=\s*"\d+\.\d+\.\d+"/);
console.log('Official Kun Online adaptive launcher icon and release version verified.');
