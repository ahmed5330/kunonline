import assert from 'node:assert/strict';
import fs from 'node:fs';
import {recoverOrderContacts} from '../src/customer-contact-evidence.js';
const read=path=>fs.readFileSync(new URL('../'+path,import.meta.url),'utf8');
const mirror={type:'contact',channel:'phone',intent:'call',at:'2026-10-18T10:01:03.000Z',byName:'Randa'};
const screened={type:'contact',channel:'phone',intent:'screened',at:'2026-10-18T10:04:11.000Z',byName:'Randa'};
const contact={type:'contact',channel:'phone',intent:'contact',at:'2026-10-18T10:30:11.000Z',byName:'Randa'};
const unrelated={type:'state',state:'confirmed',at:'2026-10-18T10:31:11.000Z'};
const claim={type:'contact_claimed',at:'2026-10-18T10:31:13.000Z'};
const common=recoverOrderContacts([mirror,screened,contact],[mirror,screened,contact,unrelated,claim]);
assert.equal(common.contactCount,3,'count browser attempts + Android screened calls');
assert.equal(common.screenedContactCount,1,'screened subset remains separate');
assert.equal(common.recoveredContactCount,0,'mirrored history not counted twice');
const erasedLog=recoverOrderContacts('[]',[mirror,screened,unrelated]);
assert.equal(erasedLog.contactCount,2,'recover logged calls from history after contact_log reset');
assert.equal(erasedLog.recoveredContactCount,2);
const partial=recoverOrderContacts([mirror],[mirror,screened,contact]);
assert.equal(partial.contactCount,3,'recover missing history attempts without double count');
assert.equal(partial.contactLog.length,3);
const oldStamp='2026-09-30T14:03:08.191Z';
const legacy=recoverOrderContacts(JSON.stringify([oldStamp]),[{type:'contact',at:oldStamp,by:'Support Agent'}]);
assert.equal(legacy.contactCount,1,'legacy ISO contact_log is preserved and its history mirror is deduplicated');
const olderNoHistory=recoverOrderContacts(JSON.stringify([oldStamp]),[]);
assert.equal(olderNoHistory.contactCount,1,'legacy timestamp still counts even without history');
const noEvidence=recoverOrderContacts('[]',[unrelated,claim,{type:'whatsapp',at:oldStamp}, {type:'internal_note',note:'called',at:oldStamp}]);
assert.equal(noEvidence.contactCount,0,'do not invent calls from notes, claims, state changes');
const repeated=recoverOrderContacts([mirror,mirror],[mirror,mirror]);
assert.equal(repeated.contactCount,2,'canonical repeat events remain distinct while mirrors are discarded');
for(const path of ['src/production-customer-service.js','src/customer-service.js','src/customer-service-period-v111.js']){
 const text=read(path);
 assert.match(text,/recoverOrderContacts/,`${path} must use the shared contact recovery helper`);
 assert.match(text,/contactCount:contacts.contactCount/,`${path} must not report screened-only counts`);
}
const prod=read('src/production-customer-service.js');
assert.match(prod,/recoverOrderContacts\(saved.contactLog,saved.history\)\.contactCount/,'POST and GET use the same counting rules');
assert.match(prod,/intent==='screened'/,'screened subset is available separately');
const ui=read('public/v2/modules-v31-customer-service.js');
assert.match(ui,/data-cs-contact-count/,'web displays corrected authoritative board count');
const android=read('android/app/src/main/java/com/kunonline/callerid/CustomerServiceApi.kt');
assert.match(android,/o\.optInt\("contactCount"/,'Android parses the same corrected server count');
console.log('PASS contact regression: legacy attempts, screened calls, recoverable history, mirrored events and web/Android parity');
