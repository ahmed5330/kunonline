import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
import {createMobileSync} from '../src/mobile-state-sync.js';
globalThis.crypto ||= webcrypto;
let now = 0, calls = 0;
const handle = createMobileSync({clock: () => now, ttlMs: 100});
let state = {orders: [{id:'a',state:'pending'},{id:'b',state:'confirmed'}], products: [{id:'p'}], secretField:'visible'};
let status = 200;
const poll = async (cursor='',cookie='user-a',query='clientId=A') => {
  const request = new Request(`https://example.test/api/mobile/state-sync?${query}&cursor=${cursor}`,{headers:{Cookie:cookie}});
  const response = await handle({request,load:async source => {
    calls++;
    assert.equal(new URL(source.url).pathname,'/api/state');
    assert.equal(new URL(source.url).searchParams.has('cursor'),false);
    assert.equal(source.headers.get('Cookie'),cookie);
    return Response.json(status===200?state:{error:'Denied'},{status});
  }});
  return {status:response.status,data:await response.json()};
};
let first = (await poll()).data;
assert.equal(first.mode,'reset');
assert.equal((await poll(first.cursor)).data.mode,'unchanged');
assert.equal(calls,2,'unchanged must still authorize through source');
state={orders:[{id:'c',state:'pending'},{id:'a',state:'shipped'}],products:[]};
let changed=(await poll(first.cursor)).data;
assert.equal(changed.mode,'delta');
assert.deepEqual(changed.orders.removed,['b']);
assert.deepEqual(changed.orders.upsert,state.orders);
assert.deepEqual(changed.orders.ids,['c','a']);
assert.deepEqual(changed.fields,{products:[]});
assert.deepEqual(changed.removedFields,['secretField']);
assert.equal((await poll(changed.cursor,'user-b')).data.mode,'reset','no cross-session baseline');
assert.equal((await poll(changed.cursor,'user-a','clientId=B')).data.mode,'reset','no cross-tenant baseline');
status=403;
assert.equal((await poll(changed.cursor)).status,403,'revocation overrides known cursor');
status=401;
assert.equal((await poll(changed.cursor)).status,401);
status=200;
now=101;
assert.equal((await poll(changed.cursor)).data.mode,'reset','expired baseline safely rebases');
state={orders:[{id:'a',state:'x'},{id:'a',state:'y'}]};
first=(await poll()).data;
state.orders[1].state='z';
assert.equal((await poll(first.cursor)).data.mode,'reset','ambiguous IDs cannot produce deltas');
const bounded=createMobileSync({maxBytes:2});
const load=async()=>Response.json({orders:[]});
first=await (await bounded({request:new Request('https://example.test/api/mobile/state-sync'),load})).json();
assert.equal((await (await bounded({request:new Request(`https://example.test/api/mobile/state-sync?cursor=${first.cursor}`),load})).json()).mode,'reset');
console.log('Mobile sync: updates, deletions, order, empty lists, scope isolation, auth revocation, expiry and eviction passed.');
