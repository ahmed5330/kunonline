import {readFile} from 'node:fs/promises';
const runner=await readFile(new URL('../src/execution-runner.js',import.meta.url),'utf8');
const entry=await readFile(new URL('../src/index-commerce-v10.js',import.meta.url),'utf8');
const appWrangler=await readFile(new URL('../wrangler.preview.toml',import.meta.url),'utf8');
const syncWrangler=await readFile(new URL('../wrangler.sync.preview.toml',import.meta.url),'utf8');
const must=(ok,msg)=>{if(!ok)throw new Error(msg)};
for(const action of ['add_tag','add_note','assign_agent','notify_team','send_whatsapp'])must(runner.includes(`case '${action}'`),`Missing adapter ${action}`);
must(runner.includes('adapter_not_configured'),'Unknown actions must fail closed');
must(runner.includes("status='running'"),'Jobs must claim running state');
must(runner.includes("status='completed'"),'Completed state missing');
must(runner.includes("'dead_letter'"),'Dead-letter handling missing');
must(runner.includes("status IN ('queued','failed')"),'Failed jobs must become eligible for scheduled retries');
must(runner.includes('Math.pow(2'),'Exponential retry backoff missing');
must(entry.includes('/api/execution-jobs/run'),'Manual queue runner endpoint missing');
must(entry.includes("controller?.cron==='*/5 * * * *'"),'Queue cron routing must remain isolated from shipping tracking cron');
must(/crons\s*=\s*\[\s*\]/m.test(appWrangler),'App Worker must own zero Cron Triggers after scheduler handoff');
must(syncWrangler.includes('"*/5 * * * *"'),'Dedicated scheduler five-minute queue/recovery cron missing');
must(syncWrangler.includes('"0 */2 * * *"'),'Dedicated scheduler shipping/Meta cron missing');
must(syncWrangler.includes('entrypoint = "SyncEntrypoint"'),'Dedicated scheduler must delegate through private app RPC');
console.log('Execution runner checks passed: adapters, retries, dead-letter, app zero-Cron ownership and dedicated scheduler isolation.');
